#!/usr/bin/env python3
"""Slice complete props out of assets/tileset/platformer.png.

Why this exists
---------------
platformer.png is a 9x5 grid of 64px cells, but the grid does not match the
art.  Several drawings are taller than one cell, so slicing on the grid alone
yields half a tree -- which is exactly what the game used to render.

Every rectangle below was established by measurement, not by eye:

  * Border-continuity testing walks each shared border between adjacent cells
    and counts how many opaque pixels continue across with a matching colour.
    A high count means the drawing genuinely crosses the cell boundary and the
    two cells are one object.

      tile 31 (4,3) -> down -> tile 40 (4,4) : 38/46 pixels continue
      tile 32 (5,3) -> down -> tile 41 (5,4) : 32/46 pixels continue

    Those two are the trees.  Nothing else on the sheet crosses a border with
    that strength except terrain tiles, which are meant to tile seamlessly.

  * Inside a cell, flood fill separates drawings that merely share a cell.
    Cell (4,2) for instance holds four unrelated things: a crystal, a clipped
    crystal fragment, a red-berried branch and a second crystal.

Objects that are clipped by the sheet itself (a crystal in cell (4,2) is cut
off mid-shape by the artist) are deliberately excluded -- there is no way to
reconstruct the missing half.

Re-run this after changing the sheet.  It writes assets/objects.png and
src/Objects.h.
"""

from PIL import Image
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "assets", "tileset", "platformer.png")
OUT_PNG = os.path.join(ROOT, "assets", "objects.png")
OUT_H = os.path.join(ROOT, "src", "Objects.h")

TS = 64
KEY = (0xDB, 0x3F, 0xFD)      # magenta chroma key


def on(px, x, y):
    r, g, b, a = px[x, y]
    return a >= 24 and (r, g, b) != KEY


# name, (cell col, cell row), (local x, local y, w, h), cells tall
#   local coords are relative to the cell's top-left corner.
#   When the rect is None the whole multi-cell block is cropped to content.
SPEC = [
    # --- multi-cell: the drawings that were being cut in half ---------------
    ("tree_green",   (4, 3), None,              2),
    ("tree_autumn",  (5, 3), None,              2),
    # --- single-cell, complete ----------------------------------------------
    ("boulder_deep", (5, 1), None,              1),
    ("boulder_teal", (8, 1), None,              1),
    ("bush",         (3, 3), None,              1),
    ("crystal",      (4, 2), (4, 14, 27, 18),   1),
    ("branch_red",   (4, 2), (34, 35, 26, 29),  1),
    ("shard",        (5, 2), None,              1),
]


def main():
    im = Image.open(SRC).convert("RGBA")
    px = im.load()

    slices = []
    for name, (c, r), rect, cells_tall in SPEC:
        if rect is None:
            # crop the whole block, then shrink to the drawn content
            box = (c * TS, r * TS, c * TS + TS, r * TS + TS * cells_tall)
            block = im.crop(box)
            bb = block.getbbox()
            if bb is None:
                raise SystemExit("object %s is empty" % name)
            img = block.crop(bb)
        else:
            lx, ly, w, h = rect
            img = im.crop((c * TS + lx, r * TS + ly,
                           c * TS + lx + w, r * TS + ly + h))
        slices.append((name, img, cells_tall))
        print("  %-13s %3dx%-3d  (%d cell%s tall)"
              % (name, img.size[0], img.size[1], cells_tall,
                 "" if cells_tall == 1 else "s"))

    PAD = 2
    total_w = sum(s[1].size[0] for s in slices) + PAD * (len(slices) + 1)
    total_h = max(s[1].size[1] for s in slices) + PAD * 2
    atlas = Image.new("RGBA", (total_w, total_h), (0, 0, 0, 0))
    x = PAD
    rects = []
    for name, img, cells_tall in slices:
        atlas.paste(img, (x, PAD))
        rects.append((name, x, PAD, img.size[0], img.size[1], cells_tall))
        x += img.size[0] + PAD
    atlas.save(OUT_PNG)
    print("\n  atlas %dx%d -> assets/objects.png" % (total_w, total_h))

    # ---------------- emit src/Objects.h -----------------------------------
    L = []
    L.append("// Objects.h -- GENERATED by tools/build_objects.py. DO NOT EDIT.")
    L.append("//")
    L.append("// Complete props sliced out of assets/tileset/platformer.png.")
    L.append("//")
    L.append("// The source sheet is a 9x5 grid of 64px cells, but the art does not")
    L.append("// respect that grid: the two trees are each drawn across two cells, so")
    L.append("// slicing per cell rendered a half tree.  Every entry below was")
    L.append("// assembled from its component cells first, then cropped to content.")
    L.append("//")
    L.append("// Anchoring: these props stand ON the ground, so a placement stores the")
    L.append("// anchor point and the sprite is drawn with the anchor at its bottom")
    L.append("// centre.")
    L.append("#pragma once")
    L.append("")
    L.append("namespace Objects {")
    L.append("")
    L.append("    struct Rect { int x, y, w, h; };")
    L.append("")
    L.append("    enum Id {")
    for i, (name, *_rest) in enumerate(rects):
        L.append("        OBJ_%s = %d," % (name.upper(), i))
    L.append("        OBJ_COUNT")
    L.append("    };")
    L.append("")
    L.append("    inline const Rect RECTS[OBJ_COUNT] = {")
    for name, rx, ry, rw, rh, _ct in rects:
        L.append("        { %4d, %2d, %3d, %3d },   // %s" % (rx, ry, rw, rh, name))
    L.append("    };")
    L.append("")
    L.append("    // Source tiles tall.  A 2 means the sheet split it across two cells;")
    L.append("    // such an object must never be sliced per cell again.")
    L.append("    inline const int TILES_TALL[OBJ_COUNT] = {")
    for name, _rx, _ry, _rw, _rh, ct in rects:
        L.append("        %d,   // %s" % (ct, name))
    L.append("    };")
    L.append("")
    L.append("}  // namespace Objects")
    L.append("")

    with open(OUT_H, "w") as f:
        f.write("\n".join(L))
    print("  wrote src/Objects.h")


if __name__ == "__main__":
    main()
